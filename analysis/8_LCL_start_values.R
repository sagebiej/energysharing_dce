## -------------------------------------------------------------- ##
## Access function                                                 ##
## -------------------------------------------------------------- ##
# Returns the starting values for K classes. With RUN_SEARCH = TRUE the
# solution of the new search is used if it exists.

lcl_start_values <- function(K, covariates = TRUE) {
  key <- paste0(if (covariates) "sociodem" else "nocov", "_K", K)
  if (isTRUE(RUN_SEARCH)) {
    f <- file.path(SEARCH_DIR, "search_start_values.rds")
    if (file.exists(f)) {
      found <- readRDS(f)
      if (!is.null(found[[key]])) {
        cat("Starting values for", key, "from the new multi-start search\n")
        return(found[[key]])
      }
    }
    cat("NOTE: no search result for", key, "- stored starting values are used\n")
  }
  if (is.null(LCL_START_VALUES[[key]])) stop("No starting values for ", key)
  LCL_START_VALUES[[key]]
}

# Start counts for Table A.2: from the new search or from the record above
lcl_search_record <- function() {
  f <- file.path(SEARCH_DIR, "search_record.csv")
  if (isTRUE(RUN_SEARCH) && file.exists(f)) return(read.csv(f, stringsAsFactors = FALSE))
  LCL_SEARCH_RECORD
}

