######################################################################
### Study       : DCE Energy Sharing                               ###
### Description : Starting values of the latent class models       ###
###               (WTP space, 2 to 7 classes, with and without     ###
###               socio-demographics in the class allocation)      ###
###               and the record of the multi-start search that    ###
###               produced them.                                   ###
### Output      : objects in the workspace, nothing is written     ###
### Date        : 24.09.2026                                        ###
######################################################################
###
### Why starting values are needed
###   Latent class models have many local optima. A single estimation
###   from default starting values does not reliably reach the best
###   solution (e.g. the five-class model with socio-demographics
###   converges to LL = -8130.70 instead of -8120.71 when started from
###   the solution without socio-demographics).
###   The reported models are therefore the best solutions of a
###   multi-start search (random, perturbed, nested, split and drop
###   starting values; see Supplementary material A.3). The search took
###   several nights.
###
### What this script contains
###   LCL_START_VALUES   the parameter vector of the best solution for
###                      each model. 10_LCL_WTP_K_Classes.R starts from
###                      these values and re-estimates every model
###                      completely (including standard errors).
###   LCL_REPORTED_LL    the log-likelihoods reported in the paper, used
###                      to check that the replication reaches them.
###   LCL_SEARCH_RECORD  number of starts and number of starts reaching
###                      the best solution (Table A.2).
###
### RUN_SEARCH = TRUE (set in 0_Main_Script.R)
###   9_LCL_multistart_search.R repeats the search from random starting
###   values. lcl_start_values() then returns the solutions found by
###   that search instead of the stored ones, and Table A.2 reports the
###   start counts of the new search.
###
### Parameter names: <parameter>_<class>, classes a, b, c, ...
###   bprice    price (scale) parameter          asc   status quo constant
###   b...      WTP of the attribute levels      delta class constant
###   delta_inter_<variable>  socio-demographic effect on class membership
######################################################################

